// The old-URL mapping table (src/data/old-url-map.json): what became of
// every URL the WordPress site had. Each module under url-map/ contributes
// one class of old URLs (posts and pages, feeds, date archives, …); the
// table keeps the facts behind them in named sections, and in `urls` what
// the new site must answer for each URL (read by the URL checker, and later
// by the redirect generation).
import type { ExpectedUrl } from '../url-checker/expected-urls.ts';
import type { ConvertedEntry } from './convert.ts';
import * as sources from './url-map/index.ts';
import type { WordPressSite } from './wordpress.ts';

export type UrlMapInput = {
	site: WordPressSite;
	/** The converted posts and pages, by WordPress ID. */
	entries: ConvertedEntry[];
};

export type UrlMapPart = {
	/** Named sections of the table, e.g. `content`; each section comes from one module. */
	sections?: Record<string, unknown[]>;
	/** What the new site must answer for each old URL. */
	urls?: ExpectedUrl[];
};

/** One class of old URLs. */
export type UrlSource = (input: UrlMapInput) => UrlMapPart;

/**
 * An archive at `url` listing `count` posts: its first page there, and pages
 * 2…N at `<url>page/N/`, posts_per_page posts to a page as on WordPress.
 */
export function paginated(url: string, count: number, site: WordPressSite): ExpectedUrl[] {
	const perPage = Number(site.option('posts_per_page'));
	if (!(perPage > 0)) throw new Error(`WordPress option posts_per_page is ${site.option('posts_per_page')}`);
	const pages = Math.max(1, Math.ceil(count / perPage));
	return Array.from({ length: pages }, (_, i) => ({ url: i === 0 ? url : `${url}page/${i + 1}/`, expect: 'page' }));
}

export const MAPPING_TABLE_ABOUT =
	'Old-URL mapping table of the WordPress site: generated by `npm run convert-wordpress` from the backup; ' +
	'sections hold the facts, urls what the new site answers for each old URL (see docs/migration-log.md).';

export function mappingTable(input: UrlMapInput, source: string): string {
	const sections: Record<string, unknown[]> = {};
	const urls = new Map<string, ExpectedUrl>();
	for (const [name, contribute] of Object.entries(sources as Record<string, UrlSource>)) {
		const part = contribute(input);
		for (const [key, value] of Object.entries(part.sections ?? {})) {
			if (key in sections) throw new Error(`Two url-map modules write the section ${key} (${name})`);
			sections[key] = value;
		}
		for (const entry of part.urls ?? []) {
			const existing = urls.get(entry.url);
			if (existing && JSON.stringify(existing) !== JSON.stringify(entry)) {
				throw new Error(`Conflicting expectations for ${entry.url}: ${JSON.stringify(existing)}, ${JSON.stringify(entry)}`);
			}
			urls.set(entry.url, entry);
		}
	}
	const sortedUrls = [...urls.values()].sort((a, b) => Buffer.compare(Buffer.from(a.url), Buffer.from(b.url)));
	const table: Record<string, unknown> = { about: MAPPING_TABLE_ABOUT, source };
	for (const key of Object.keys(sections).sort()) table[key] = sections[key];
	table.urls = sortedUrls;
	return formatTable(table);
}

/** JSON with one array item per line, so a change to one entry is a one-line diff. */
function formatTable(table: Record<string, unknown>): string {
	const lines = Object.entries(table).map(([key, value]) => {
		if (!Array.isArray(value)) return `\t${JSON.stringify(key)}: ${JSON.stringify(value)}`;
		if (value.length === 0) return `\t${JSON.stringify(key)}: []`;
		return `\t${JSON.stringify(key)}: [\n${value.map((item) => `\t\t${JSON.stringify(item)}`).join(',\n')}\n\t]`;
	});
	return `{\n${lines.join(',\n')}\n}\n`;
}
